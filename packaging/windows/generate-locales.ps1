<#
.SYNOPSIS
  Generates WiX components for the staged locale catalogs.

.DESCRIPTION
  The tray loads locales/<code>.json at runtime. WiX does not expand directory
  wildcards in a ComponentGroup, so this script enumerates the staged files
  and emits a deterministic source fragment for the MSI build. Stable component
  GUIDs are generated by WiX from the directory and file identity.
#>
[CmdletBinding()]
param(
    [Parameter(Mandatory = $true)]
    [string]$SourceDir,

    [string]$OutputPath = (Join-Path $PSScriptRoot 'ProductLocales.wxs')
)

$ErrorActionPreference = 'Stop'
$localeDir = Join-Path $SourceDir 'locales'
if (-not (Test-Path -LiteralPath $localeDir)) {
    throw "Locale directory not found: $localeDir"
}

$files = @(Get-ChildItem -LiteralPath $localeDir -Filter '*.json' -File | Sort-Object Name)
if ($files.Count -eq 0) {
    throw "No locale catalogs found in $localeDir"
}

function Escape-Xml([string]$value) {
    return [System.Security.SecurityElement]::Escape($value)
}

$lines = New-Object System.Collections.Generic.List[string]
$lines.Add('<?xml version="1.0" encoding="utf-8"?>')
$lines.Add('<Wix xmlns="http://wixtoolset.org/schemas/v4/wxs">')
$lines.Add('  <Fragment>')
$lines.Add('    <ComponentGroup Id="LocaleComponents">')

foreach ($file in $files) {
    $stem = [System.IO.Path]::GetFileNameWithoutExtension($file.Name)
    $safe = $stem -replace '[^A-Za-z0-9_]', '_'
    $componentId = 'Locale_' + $safe
    $fileId = 'LocaleFile_' + $safe
    $source = '$(var.SourceDir)\locales\' + $file.Name

    $lines.Add('      <Component Id="' + $componentId + '" Directory="LOCALESFOLDER" Guid="*">')
    $lines.Add('        <File Id="' + $fileId + '" Source="' + (Escape-Xml $source) + '" />')
    $lines.Add('      </Component>')
}

$lines.Add('    </ComponentGroup>')
$lines.Add('  </Fragment>')
$lines.Add('</Wix>')

$outputDir = Split-Path -Parent $OutputPath
if (-not (Test-Path -LiteralPath $outputDir)) {
    New-Item -ItemType Directory -Force -Path $outputDir | Out-Null
}
Set-Content -LiteralPath $OutputPath -Value ($lines -join [Environment]::NewLine) -Encoding UTF8
Write-Output ("generated {0} locale components in {1}" -f $files.Count, $OutputPath)
