#!/usr/bin/env bash
# Optional local Git forge (Forgejo) in Docker. Loopback only: no external
# traffic, no cloud account, data stays in /opt/wsl-forgejo/data.

install_forgejo() {
    [[ ${WITH_FORGE} -eq 1 ]] || return 0

    if [[ ${WITH_DOCKER} -ne 1 ]]; then
        warn "Forgejo needs Docker; skipping (--no-docker)"
        return 0
    fi

    local dir=/opt/wsl-forgejo
    local admin_user=${FORGE_ADMIN_USER:-forge}
    local password="" secret="" image="" uid gid

    uid=$(id -u "$TARGET_USER")
    gid=$(id -g "$TARGET_USER")

    install -d -m 0755 "$dir"
    install -d -m 0750 -o "$TARGET_USER" -g "$TARGET_USER" "$dir/data"
    install -m 0644 "${SCRIPT_DIR}/docker/forgejo.yaml" "${dir}/compose.yaml"

    if [[ -f ${dir}/.env ]]; then
        secret=$(awk -F= '/^FORGEJO_SECRET_KEY=/{print $2; exit}' "${dir}/.env" | tr -d '\r')
        admin_user=$(awk -F= '/^FORGEJO_ADMIN_USER=/{print $2; exit}' "${dir}/.env" | tr -d '\r')
        password=$(awk -F= '/^FORGEJO_ADMIN_PASSWORD=/{print $2; exit}' "${dir}/.env" | tr -d '\r')
        image=$(awk -F= '/^FORGEJO_IMAGE=/{print $2; exit}' "${dir}/.env" | tr -d '\r')
    fi
    [[ -n ${FORGE_ADMIN_USER:-} ]] && admin_user=$FORGE_ADMIN_USER
    [[ -n ${admin_user} ]] || admin_user=forge

    # Forgejo reserves "admin" (and a few routes); keep .env valid and stable.
    if [[ ${admin_user} == admin || ! ${admin_user} =~ ^[a-z0-9][a-z0-9._-]{0,31}$ ]]; then
        warn "Forgejo reserves '${admin_user}'; using 'forge' instead"
        admin_user=forge
    fi

    # Always normalise .env: keep what is valid, regenerate what is missing.
    [[ -n ${secret} ]] ||
        secret=$(openssl rand -hex 32 2>/dev/null || tr -dc 'a-f0-9' </dev/urandom | head -c 64)
    if [[ ${#password} -lt 8 ]]; then
        password=$(openssl rand -base64 32 2>/dev/null | tr -dc 'A-Za-z0-9' | head -c 20)
        [[ ${#password} -ge 16 ]] ||
            password=$(tr -dc 'A-Za-z0-9' </dev/urandom | head -c 20)
    fi

    cat >"${dir}/.env" <<EOF
# Generated by wsl-provision on $(date -u +%Y-%m-%dT%H:%M:%SZ)
FORGEJO_SECRET_KEY=${secret}
FORGEJO_ADMIN_USER=${admin_user}
FORGEJO_ADMIN_PASSWORD=${password}
FORGEJO_UID=${uid}
FORGEJO_GID=${gid}
EOF
    if [[ -n ${image} ]]; then
        printf 'FORGEJO_IMAGE=%s\n' "$image" >>"${dir}/.env"
    fi
    chown "$TARGET_USER:$TARGET_USER" "${dir}/.env"
    chmod 0600 "${dir}/.env"

    info "Starting Forgejo (loopback only)"
    if ! run_as_user "$TARGET_USER" "cd ${dir} && docker compose up -d" >/dev/null 2>&1; then
        warn "docker compose up failed; last container logs:"
        run_as_user "$TARGET_USER" "cd ${dir} && docker compose logs --tail=30" 2>&1 |
            sed 's/^/    /' >&2 || true
        return 0
    fi

    local attempt
    for attempt in $(seq 1 60); do
        curl -fsS -m 2 http://127.0.0.1:3000/api/healthz >/dev/null 2>&1 && break
        sleep 1
    done
    if ! curl -fsS -m 2 http://127.0.0.1:3000/api/healthz >/dev/null 2>&1; then
        warn "Forgejo did not answer on 127.0.0.1:3000 within 60s"
        return 0
    fi

    local exists=0
    if run_as_user "$TARGET_USER" "cd ${dir} && docker compose exec -T -u git forgejo forgejo admin user list" 2>/dev/null |
        awk -v u="$admin_user" '$2 == u { found = 1 } END { exit !found }'; then
        exists=1
    fi

    if [[ ${exists} -eq 0 ]]; then
        if run_as_user "$TARGET_USER" "cd ${dir} && docker compose exec -T -u git forgejo forgejo admin user create --admin --username '${admin_user}' --password '${password}' --email '${admin_user}@wsl.local' --must-change-password=false" >/dev/null 2>&1; then
            ok "Forgejo admin '${admin_user}' created"
        else
            warn "could not create the Forgejo admin - finish setup at http://localhost:3000"
        fi
    else
        ok "Forgejo admin '${admin_user}' already exists"
    fi

    # .env is the source of truth: make sure its password actually works.
    if ! curl -fsS -m 5 -u "${admin_user}:${password}" \
        "http://127.0.0.1:3000/api/v1/user" >/dev/null 2>&1; then
        if run_as_user "$TARGET_USER" "cd ${dir} && docker compose exec -T -u git forgejo forgejo admin user change-password --username '${admin_user}' --password '${password}' --must-change-password=false" >/dev/null 2>&1; then
            ok "admin password aligned with ${dir}/.env"
        else
            warn "could not align the admin password; check ${dir}/.env"
        fi
    fi

    # Smoke test 1: authenticated API + a private test repository.
    if ! curl -fsS -m 5 -u "${admin_user}:${password}" \
        "http://127.0.0.1:3000/api/v1/repos/${admin_user}/hello" >/dev/null 2>&1; then
        curl -fsS -m 10 -u "${admin_user}:${password}" \
            -H 'Content-Type: application/json' \
            -d '{"name":"hello","description":"created by wsl-provision","private":true,"auto_init":true}' \
            "http://127.0.0.1:3000/api/v1/user/repos" >/dev/null 2>&1 ||
            warn "could not create the test repository"
    fi

    # Smoke test 2: real Git smart-HTTP (never prompt; bounded by timeout).
    local basic
    basic=$(printf '%s:%s' "$admin_user" "$password" | base64 -w0)
    if GIT_TERMINAL_PROMPT=0 timeout 20 git -c credential.helper= \
        -c "http.extraHeader=Authorization: Basic ${basic}" \
        ls-remote "http://localhost:3000/${admin_user}/hello.git" >/dev/null 2>&1; then
        ok "Git over HTTP verified (${admin_user}/hello)"
    else
        warn "Git smart-HTTP check failed; open http://localhost:3000 and clone manually"
    fi

    printf '  %s[forge]%s http://localhost:3000  admin=%s  password in %s/.env\n' \
        "$C_OK" "$C_RESET" "$admin_user" "$dir"
    ok "Forgejo data lives in ${dir}/data (SQLite + repositories)"
}
